/**
 * Route table — drives client routing, build-time prerendering, the XML sitemaps, per-page
 * metadata, structured data, OG images, Markdown mirrors and llms.txt. Add a page here and it is
 * rendered, indexed and listed automatically.
 */

export type PageKey =
  | 'home'
  | 'pricing'
  | 'about'
  | 'privacy'
  | 'terms'
  | 'services'
  | 'service'
  | 'guides'
  | 'guide'
  | 'work'
  | 'caseStudy'
  | 'notFound';

export type SitemapGroup = 'pages' | 'services' | 'guides' | 'work';

export interface RouteMeta {
  title: string;
  description: string;
  ogType?: 'website' | 'article';
  /** Defaults to true; the 404 page is the only non-indexable route. */
  indexable?: boolean;
}

export interface RouteDef {
  path: string;
  page: PageKey;
  /** Slug for service / guide / case-study pages. */
  slug?: string;
  meta: RouteMeta;
  jsonLd: Record<string, unknown>[];
  /** Declared ISO date of the last meaningful content change (fallback when git history is unavailable). */
  lastmod: string;
  /** Source files/dirs whose last git commit date becomes the sitemap lastmod. */
  sources: string[];
  /** Sitemap file this URL is listed in. */
  sitemap: SitemapGroup;
  /** Images for the image sitemap (absolute paths on this site). */
  images: { src: string; title: string }[];
  /** Whether a Markdown mirror (<path>.md) is generated. */
  markdown: boolean;
}

