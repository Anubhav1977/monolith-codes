const serviceRoutes: RouteDef[] = SERVICES.map((s) => {
  const path = `/services/${s.slug}`;
  const url = absoluteUrl(path);
  const offer = s.tier ? usdOffer(s.tier, url, `${s.name} — starting price`) : undefined;
  return {
    path,
    page: 'service',
    slug: s.slug,
    lastmod: s.updated,
    sources: ['src/pages/ServicePage.tsx', 'src/content/services.ts'],
    sitemap: 'services',
    markdown: true,
    images: [{ src: s.image.src, title: s.image.alt }],
    meta: { title: s.metaTitle, description: s.metaDescription },
    jsonLd: [
      webPageLd(path, s.h1, s.metaDescription, 'WebPage', { mainEntity: { '@id': `${url}#service` } }, ogImageUrl(path)),
      {
        '@type': 'Service',
        '@id': `${url}#service`,
        name: s.name,
        serviceType: s.serviceType,
        description: s.summary,
        url,
        image: absoluteUrl(s.image.src),
        provider: { '@id': ORG_ID },
        areaServed: AREA_SERVED,
        ...(offer ? { offers: offer } : {}),
      },
      faqLd(`${url}#faq`, s.faqs),
      breadcrumbLd([crumbHome, { name: 'Services', path: '/services' }, { name: s.name, path }]),
    ],
  };
});

const guideRoutes: RouteDef[] = GUIDES.map((g) => {
  const path = `/guides/${g.slug}`;
  const url = absoluteUrl(path);
  return {
    path,
    page: 'guide',
    slug: g.slug,
    lastmod: g.updated,
    sources: ['src/pages/GuidePage.tsx', 'src/content/guides.ts'],
    sitemap: 'guides',
    markdown: true,
    images: [],
    meta: { title: g.metaTitle, description: g.metaDescription, ogType: 'article' },
    jsonLd: [
      webPageLd(path, g.h1, g.metaDescription, 'WebPage', { mainEntity: { '@id': `${url}#article` } }, ogImageUrl(path)),
      {
        '@type': 'Article',
        '@id': `${url}#article`,
        headline: g.h1,
        description: g.metaDescription,
        url,
        mainEntityOfPage: { '@id': `${url}#webpage` },
        image: { '@type': 'ImageObject', url: ogImageUrl(path), width: 1200, height: 630 },
        datePublished: g.published,
        dateModified: g.updated,
        inLanguage: SITE.locale,
        articleSection: 'Guides',
        wordCount: g.sections
          .flatMap((sec) => sec.blocks)
          .map((b) => (typeof b === 'string' ? b : 'list' in b ? b.list.join(' ') : b.table.rows.flat().join(' ')))
          .join(' ')
          .split(/\s+/).length,
        author: { '@id': personId(g.author) },
        publisher: { '@id': ORG_ID },
        about: g.relatedServices.map((slug) => ({ '@id': `${absoluteUrl(`/services/${slug}`)}#service` })),
      },
      breadcrumbLd([crumbHome, { name: 'Guides', path: '/guides' }, { name: g.name, path }]),
    ],
  };
});

