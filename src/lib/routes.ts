/** Per-page social image (generated by `npm run seo:assets` into public/og/). */
export const ogImageFor = (path: string) => `/og/${path === '/' ? 'home' : path.slice(1).replace(/\//g, '-')}.jpg`;
export const ogImageUrl = (path: string) => absoluteUrl(ogImageFor(path));

/** Markdown mirror URL for a route. */
export const markdownPathFor = (path: string) => (path === '/' ? '/index.md' : `${path}.md`);

const usdOffer = (tier: keyof typeof STARTING_PRICES_USD, url: string, name: string) => {
  const min = STARTING_PRICES_USD[tier];
  if (min === null) return undefined;
  return {
    '@type': 'Offer',
    name,
    url,
    priceCurrency: 'USD',
    price: min,
    priceSpecification: { '@type': 'PriceSpecification', minPrice: min, priceCurrency: 'USD' },
    availability: 'https://schema.org/InStock',
    seller: { '@id': ORG_ID },
  };
};

const faqLd = (id: string, items: { q: string; a: string }[]) => ({
  '@type': 'FAQPage',
  '@id': id,
  mainEntity: items.map((f) => ({
    '@type': 'Question',
    name: f.q,
    acceptedAnswer: { '@type': 'Answer', text: f.a },
  })),
});

